export function blogTitle(slug: string): string {
  return BLOG_TITLES[slug] || slug.split("-").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(" ");
}

// Up to 4 guides from the same cluster (wrapping around), so related links stay on-topic
export function relatedSlugs(slug: string): string[] {
  const cluster = BLOG_CLUSTERS.find((c) => c.slugs.includes(slug));
  if (!cluster) return [];
  const others = cluster.slugs.filter((s) => s !== slug);
  const start = cluster.slugs.indexOf(slug);
  return others
    .map((s) => ({ s, d: (cluster.slugs.indexOf(s) - start + cluster.slugs.length) % cluster.slugs.length }))
    .sort((a, b) => a.d - b.d)
    .slice(0, 4)
    .map((x) => x.s);
}
